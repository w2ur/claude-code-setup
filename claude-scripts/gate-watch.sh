#!/usr/bin/env bash
# Reports which repos have enough pull-request traffic to deserve the CI gate
# but do not carry it yet.
#
# The gate ({github-username}/.github, reusable pr-gate.yml) was deployed 2026-08-15 to the
# three repos that actually saw pull requests. That decision was correct and it
# rots on its own: a repo that opens its first PR next month gets nothing, and
# nobody notices, because "no gate" and "gate never had to fire" look identical
# from the outside. Same family as the invariant the gate itself enforces.
#
# Repos are DISCOVERED from `gh search prs`, never hand-listed, so a project
# that starts taking PRs is covered without editing this file — the same
# principle as usage-watch.sh discovering hosts from the Vercel API and
# model-watch.sh discovering models from wrangler.toml. That principle is not
# decorative here: the 2026-08-15 scope decision was taken from a hand-picked
# loop over 12 repos and MISSED `my-boardgame-app` and `my-bias-app`, both of which had PRs.
# One `gh search prs --owner` call finds every repo in one request.
#
# Reports state; never edits config, never opens a PR. Applying the gate is one
# file and a PR you review — see the command it prints.
#
# Reads no local tree, so there is no DEV_DIR to redirect (same as
# distribution-watch.sh); it queries the GitHub API and nothing else.
#
# NOTE: `gh` reads its OAuth token from the login keychain, which a crontab job
# cannot see — a cron-scheduled run of this script would report HTTP 401 on
# every repo. Schedule it as a launchd LaunchAgent, never from crontab.
#
# Exit: 0 every repo over threshold carries a gate; 1 at least one does not;
# 2 the check could not run (no gh, no jq, not authenticated, search failed) —
# which must be read as UNKNOWN, never as healthy.
set -euo pipefail

DAYS="${GATE_WATCH_DAYS:-90}"
MIN_PRS="${GATE_WATCH_MIN_PRS:-3}"
JSON_OUTPUT=false
[ "${1:-}" = "--json" ] && JSON_OUTPUT=true

# Repos that will never carry a gate, each with its reason — same discipline as
# vigie's NO_CLAUDE_MD_EXPECTED. An entry without a reason is a bug.
exempt_reason() {
  case "$1" in
    midas-core) echo "a mirror generated by my-trading-app/scripts/sync_core.py — every PR there is an artefact" ;;
    {github-username})       echo "the GitHub profile README — one file, no code to check" ;;
    *)          echo "" ;;
  esac
}

command -v gh >/dev/null 2>&1 || { echo "WARN: gh not found — cannot run. Add /opt/homebrew/bin to PATH." >&2; exit 2; }
command -v jq >/dev/null 2>&1 || { echo "WARN: jq not found — cannot run." >&2; exit 2; }

# Authentication is checked explicitly rather than inferred from an empty
# result set: an unauthenticated `gh search prs` returns zero rows, which is
# byte-identical to "no repo has any PRs" — the exact ambiguity this script
# exists to refuse elsewhere.
gh auth status >/dev/null 2>&1 || {
  echo "WARN: gh is not authenticated — cannot tell 'no PRs' from 'no access'." >&2
  echo "      If this ran from crontab, that is the cause: gh's token lives in the" >&2
  echo "      login keychain, which a cron job cannot read. Use a LaunchAgent." >&2
  exit 2
}

OWNER="${GATE_WATCH_OWNER:-$(gh api user --jq .login 2>/dev/null)}"
[ -n "$OWNER" ] || { echo "WARN: could not resolve the GitHub account." >&2; exit 2; }

if date -v-1d +%F >/dev/null 2>&1; then
  SINCE=$(date -v-"${DAYS}"d +%F)          # BSD/macOS
else
  SINCE=$(date -d "${DAYS} days ago" +%F)  # GNU
fi

counts=$(gh search prs --owner "$OWNER" --created ">$SINCE" --limit 1000 \
           --json repository --jq '.[].repository.name' 2>/dev/null | sort | uniq -c) \
  || { echo "WARN: gh search prs failed — treating as unknown." >&2; exit 2; }

# Does this repo carry a gate? Two shapes count, because my-trading-app deliberately
# keeps its own workflow rather than calling the shared one:
#   1. a caller file named pr-gate.yml
#   2. any workflow declaring a top-level `gate:` job
has_gate() {
  local repo="$1" files f content
  files=$(gh api "repos/$OWNER/$repo/contents/.github/workflows" --jq '.[].name' 2>/dev/null) || return 1
  printf '%s\n' "$files" | grep -qx 'pr-gate.yml' && return 0
  for f in $files; do
    content=$(gh api "repos/$OWNER/$repo/contents/.github/workflows/$f" --jq '.content' 2>/dev/null) || continue
    printf '%s' "$content" | base64 -d 2>/dev/null | grep -qE '^[[:space:]]{2}gate:[[:space:]]*$' && return 0
  done
  return 1
}

# Is a gate already on its way in an open PR? Without this the script reports
# MISSING for work that is done and merely awaiting review — and a watcher that
# nags about something already in flight is one you learn to skip, which is the
# failure mode that got the tech-debt rank pulled from Vigie.
gate_pending() {
  local repo="$1" nums n
  nums=$(gh pr list -R "$OWNER/$repo" --state open --limit 20 --json number --jq '.[].number' 2>/dev/null) || return 1
  for n in $nums; do
    gh api "repos/$OWNER/$repo/pulls/$n/files" --jq '.[].filename' 2>/dev/null \
      | grep -qE '^\.github/workflows/' && { echo -n "#$n"; return 0; }
  done
  return 1
}

findings=""
status=0

while read -r n repo; do
  [ -n "${repo:-}" ] || continue
  reason=$(exempt_reason "$repo")
  if [ -n "$reason" ]; then
    findings="${findings}${repo}\t${n}\texempt\t${reason}\n"
  elif [ "$n" -lt "$MIN_PRS" ]; then
    findings="${findings}${repo}\t${n}\tbelow\tunder the ${MIN_PRS}-PR threshold\n"
  elif has_gate "$repo"; then
    findings="${findings}${repo}\t${n}\tgated\t-\n"
  elif pr=$(gate_pending "$repo"); then
    findings="${findings}${repo}\t${n}\tpending\ta workflow change is open in ${pr}\n"
  else
    findings="${findings}${repo}\t${n}\tMISSING\tover threshold, no gate\n"
    status=1
  fi
done <<< "$counts"

if [ -z "$findings" ]; then
  echo "No repo under $OWNER opened a pull request since $SINCE."
  exit 0
fi

if $JSON_OUTPUT; then
  printf '%b' "$findings" | jq -R -s -c --arg since "$SINCE" --argjson min "$MIN_PRS" \
    'split("\n") | map(select(length>0) | split("\t"))
     | map({repo:.[0], prs:(.[1]|tonumber), state:.[2], note:.[3]})
     | {since:$since, threshold:$min, repos:length,
        missing:(map(select(.state=="MISSING")) | length), entries:.}'
else
  echo "CI gate coverage — PRs since $SINCE, threshold ${MIN_PRS}"
  echo
  printf '%b' "$findings" | sort -k3,3 -k2,2nr \
    | awk -F'\t' '{printf "  %-22s %3s %-3s %-8s %s\n", $1, $2, ($2==1?"PR":"PRs"), $3, $4}'
  echo
  pending=$(printf '%b' "$findings" | awk -F'\t' '$3=="pending"' | wc -l | tr -d ' ')
  gated=$(printf '%b' "$findings" | awk -F'\t' '$3=="gated"' | wc -l | tr -d ' ')
  if [ "$status" -eq 0 ] && [ "$pending" -gt 0 ]; then
    # Never call a pending gate a gate. It protects nothing until it is merged.
    echo "$gated repo(s) over the threshold carry a gate; $pending awaiting merge."
    echo "Nothing to start — but nothing is protected until those land."
  elif [ "$status" -eq 1 ]; then
    echo "At least one repo over the threshold has no gate. To add one:"
    echo
    echo "    cp ~/Dev/.github/templates/caller.yml \\"
    echo "       ~/Dev/<repo>/.github/workflows/pr-gate.yml"
    echo
    echo "then open a PR. Check whether the repo already has a ci.yml to absorb,"
    echo "and whether its build reads the environment (extra-env)."
  else
    echo "Every repo over the threshold carries a gate."
  fi
fi

exit "$status"
